"""YouTube thumbnail system: inventory, retroactive generation, QC, contact sheet, report.

  python tools/thumbnails.py inventory            # docs/thumbnails/INVENTORY.md + inventory.json
  python tools/thumbnails.py generate <slug>|all [--force]
  python tools/thumbnails.py contact              # docs/thumbnails/contact_sheet.jpg (all defaults with titles)
  python tools/thumbnails.py report               # docs/thumbnails/REPORT.md
  python tools/thumbnails.py all [--force]        # inventory -> generate all -> contact -> report

Briefs: projects/<slug>/thumbnail_brief.yaml. Engine: hiddeneco/youtube_thumbnail.py (+ CinematicThumb.tsx).
Never touches MP4s, narration, titles or descriptions; never uploads.
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

import yaml
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from hiddeneco import youtube_thumbnail as yt  # noqa: E402

OUT = ROOT / "docs" / "thumbnails"


def font(size: int, bold: bool = True):
    for f in ["DejaVuSans-Bold.ttf" if bold else "DejaVuSans.ttf"]:
        try:
            return ImageFont.truetype(f, size)
        except OSError:
            pass
    return ImageFont.load_default()


def inventory() -> list[dict]:
    rows = []
    for pj in sorted((ROOT / "projects").glob("*/project.yaml")):
        slug = pj.parent.name
        proj = yaml.safe_load(pj.read_text(encoding="utf-8")) or {}
        brief = yt.load_brief(slug) or {}
        for dy in sorted(pj.parent.glob("deliverables/*/deliverable.yaml")):
            d = yaml.safe_load(dy.read_text(encoding="utf-8")) or {}
            alias = d.get("output_alias")
            fmt = d.get("format", "")
            mp4 = ROOT / alias if alias else None
            if not mp4 or not mp4.exists():
                cand = ROOT / "output" / slug / dy.parent.name / f"{slug}--{dy.parent.name}.mp4"
                mp4 = cand if cand.exists() else None
            if fmt != "long_16x9":
                kind = "short/vertical (not a documentary)"
            else:
                kind = "documentary"
            docs = brief.get("docs_dir") if brief.get("deliverable", "documentary") == dy.parent.name else None
            existing = []
            if docs:
                existing += [str(p.relative_to(ROOT)) for p in (ROOT / docs).glob("*thumb*.png")]
                existing += [str(p.relative_to(ROOT)) for p in (ROOT / docs).glob("thumbnail_tone.png")]
            existing += [str(p.relative_to(ROOT)) for p in (ROOT / "output" / slug / dy.parent.name / "thumbnails").glob("*.png")] if (ROOT / "output" / slug / dy.parent.name / "thumbnails").exists() else []
            pkg = ROOT / docs / "youtube-package" if docs else None
            st = json.loads((pkg / "PACKAGE_STATUS.json").read_text()) if pkg and (pkg / "PACKAGE_STATUS.json").exists() else {}
            rows.append({"video_id": f"{slug}:{dy.parent.name}", "slug": slug, "deliverable": dy.parent.name, "kind": kind,
                         "title": brief.get("title") if docs else d.get("title", proj.get("title")),
                         "file": str(mp4.relative_to(ROOT)) if mp4 else None,
                         "produced": __import__("datetime").datetime.fromtimestamp(mp4.stat().st_mtime).strftime("%Y-%m-%d") if mp4 else None,
                         "status": brief.get("status", "completed") if docs else ("completed" if mp4 else "not rendered"),
                         "published": "unknown (manual uploads; nothing was uploaded by the pipeline)",
                         "docs": docs, "existing_thumbnails": existing,
                         "new_thumbnail": f"{docs}/youtube-package/thumbnail.png" if pkg and (pkg / "thumbnail.png").exists() else None,
                         "new_thumbnail_qc": st.get("thumbnail_qc"), "package_ready": st.get("package_ready")})
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / "inventory.json").write_text(json.dumps(rows, indent=2), encoding="utf-8")
    md = ["# Production inventory (thumbnails)", "", "Generated by `tools/thumbnails.py inventory`. One row per deliverable found in `projects/*/deliverables/*`.",
          "Publishing status is unknown to the pipeline (uploads are manual).", "",
          "| Video ID | Kind | Title | File | Produced | Status | Existing thumbnails | New thumbnail | QC | Package ready |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| `{r['video_id']}` | {r['kind']} | {r['title'] or '-'} | {r['file'] or '-'} | {r['produced'] or '-'} | {r['status']} | "
                  f"{len(r['existing_thumbnails'])} kept | {r['new_thumbnail'] or '-'} | {r['new_thumbnail_qc'] or '-'} | {r['package_ready'] if r['package_ready'] is not None else '-'} |")
    (OUT / "INVENTORY.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return rows


def briefs() -> list[str]:
    return sorted(p.parent.name for p in (ROOT / "projects").glob("*/thumbnail_brief.yaml"))


def generate(target: str, force: bool) -> list[dict]:
    slugs = briefs() if target == "all" else [target]
    res = []
    for i, s in enumerate(slugs):
        # distinctness is checked against every OTHER episode's current default (rendered earlier in this run or before)
        others = {o: ROOT / yt.load_brief(o)["docs_dir"] / "youtube-package" / "thumbnail.png" for o in briefs() if o != s}
        try:
            r = yt.generate(s, others=others, force=force)
            res.append({k: v for k, v in r.items() if k not in ("results", "pkg")} | {"qc": {c: x["qc"] for c, x in r.get("results", {}).items()}})
            print(f"{s}: default {r.get('default_concept')} qc {r.get('thumbnail_qc')} ready {r.get('package_ready')}")
        except Exception as e:                                        # noqa: BLE001 - keep going, record the failure
            yt._log(slug=s, event="failed", error=str(e)[:400])
            res.append({"slug": s, "status": "failed", "error": str(e)[:400]})
            print(f"{s}: FAILED {e}")
    (ROOT / "output" / "thumbnails").mkdir(parents=True, exist_ok=True)
    (ROOT / "output" / "thumbnails" / "last_run.json").write_text(json.dumps(res, indent=2, default=str))
    return res


def contact() -> Path:
    items = []
    for s in briefs():
        b = yt.load_brief(s)
        pkg = ROOT / b["docs_dir"] / "youtube-package"
        if (pkg / "thumbnail.png").exists():
            alts = sorted(pkg.glob("thumbnail-alt-*.png"))
            items.append((b["title"], pkg / "thumbnail.png", alts[0] if alts else None, b["docs_dir"].split("/")[-1]))
    tw, th = 480, 270
    cols = 2
    rows = (len(items) + cols - 1) // cols
    cw = tw * 2 + 30
    sheet = Image.new("RGB", (cols * cw + 40, rows * (th + 70) + 90), "#0B0D12")
    d = ImageDraw.Draw(sheet)
    d.text((20, 20), "The Hidden Economics: thumbnails (default | alternative)", fill="#F4F1EA", font=font(30))
    for i, (title, main, alt, ep) in enumerate(items):
        x, y = 20 + (i % cols) * cw, 80 + (i // cols) * (th + 70)
        sheet.paste(Image.open(main).convert("RGB").resize((tw, th), Image.LANCZOS), (x, y + 34))
        if alt:
            sheet.paste(Image.open(alt).convert("RGB").resize((tw, th), Image.LANCZOS).point(lambda v: int(v * 0.8)), (x + tw + 10, y + 34))
        d.text((x, y + 6), f"{ep} · {title}"[:80], fill="#D4AF5A", font=font(19))
    OUT.mkdir(parents=True, exist_ok=True)
    out = OUT / "contact_sheet.jpg"
    sheet.save(out, quality=88)
    # phone-size strip: what a viewer scrolling on a phone sees
    strip = Image.new("RGB", (len(items) * 170 + 10, 110), "#0B0D12")
    for i, (_, main, _, _) in enumerate(items):
        strip.paste(Image.open(main).convert("RGB").resize((160, 90), Image.LANCZOS), (10 + i * 170, 10))
    strip.save(OUT / "contact_sheet_phone.jpg", quality=92)
    return out


def report() -> Path:
    inv = json.loads((OUT / "inventory.json").read_text()) if (OUT / "inventory.json").exists() else inventory()
    docs = [r for r in inv if r["kind"] == "documentary"]
    last = json.loads((ROOT / "output" / "thumbnails" / "last_run.json").read_text()) if (ROOT / "output" / "thumbnails" / "last_run.json").exists() else []
    gen = [r for r in docs if r["new_thumbnail"]]
    passed = [r for r in docs if r["new_thumbnail_qc"] == "pass"]
    no_brief = [r for r in docs if not r["docs"]]
    missing_meta = []
    for s in briefs():
        st = ROOT / yt.load_brief(s)["docs_dir"] / "youtube-package" / "PACKAGE_STATUS.json"
        if st.exists() and json.loads(st.read_text()).get("metadata") == "missing":
            missing_meta.append(s)
    failed = [r for r in last if r.get("status") == "failed"]
    lines = ["# Retroactive thumbnail report", "",
             f"- Deliverables discovered: **{len(inv)}** ({len(docs)} long-form documentaries, {len(inv) - len(docs)} shorts/other)",
             f"- Documentaries with older thumbnails kept untouched: **{sum(1 for r in docs if r['existing_thumbnails'])}**",
             f"- New thumbnails generated (default + alternative): **{len(gen)}**",
             f"- Passed automated QC: **{len(passed)}**; every one still needs a human look (subject, tone, spelling, not misleading)",
             f"- Documentary deliverables without a brief (older cuts of the same story): {', '.join('`' + r['video_id'] + '`' for r in no_brief) or 'none'}",
             f"- Missing package metadata (title/description/tags): {', '.join(missing_meta) or 'none'}",
             f"- Failed generation attempts: {len(failed)}" + (": " + ", ".join(f['slug'] for f in failed) if failed else ""),
             "- Image generation: none used. Backend `svg-composite` (original vector art rendered locally with Remotion), cost US$0.00. "
             "No AI image service is configured for thumbnails and the channel rule is free/open tools only.",
             "", "## Per episode", "", "| Episode | Default | QC | Design score A / B | Package | Files |", "|---|---|---|---|---|---|"]
    for s in briefs():
        b = yt.load_brief(s)
        pkg = ROOT / b["docs_dir"] / "youtube-package"
        bj = json.loads((pkg / "thumbnail-brief.json").read_text()) if (pkg / "thumbnail-brief.json").exists() else {}
        st = json.loads((pkg / "PACKAGE_STATUS.json").read_text()) if (pkg / "PACKAGE_STATUS.json").exists() else {}
        sc = " / ".join(str(c["qc"]["design_score"]) for c in bj.get("concepts", []))
        lines.append(f"| {b['title']} | {bj.get('default', '-')} | {st.get('thumbnail_qc', '-')} | {sc} | "
                     f"{'ready' if st.get('package_ready') else ('in production' if b.get('status') == 'in_production' else 'not ready')} | `{b['docs_dir']}/youtube-package/` |")
    lines += ["", "Contact sheets: `docs/thumbnails/contact_sheet.jpg` (default and alternative per episode) and "
              "`docs/thumbnails/contact_sheet_phone.jpg` (all defaults at phone size, to spot repetition).",
              "", "Design scores are internal (contrast, legibility, clutter, distinctness) and do not predict click-through rate."]
    (OUT / "REPORT.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    return OUT / "REPORT.md"


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["inventory", "generate", "contact", "report", "all"])
    ap.add_argument("target", nargs="?", default="all")
    ap.add_argument("--force", action="store_true")
    a = ap.parse_args()
    if a.cmd == "inventory":
        print(len(inventory()), "deliverables")
    elif a.cmd == "generate":
        generate(a.target, a.force)
    elif a.cmd == "contact":
        print(contact())
    elif a.cmd == "report":
        print(report())
    else:
        inventory(); generate("all", a.force); inventory(); contact(); print(report())


if __name__ == "__main__":
    main()
