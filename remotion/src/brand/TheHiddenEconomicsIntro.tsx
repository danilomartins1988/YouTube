import React, {useMemo} from 'react';
import {AbsoluteFill, useCurrentFrame, useVideoConfig} from 'remotion';
import {clamp, easeInOut, easeOut, lerp} from '../lib/anim';

/**
 * TheHiddenEconomicsIntro: the channel's permanent 5-second cinematic intro (1920x1080).
 *
 *   0.0-1.5 s  darkness -> a perspective globe of points with glowing arcs between financial centres
 *   1.5-3.0 s  arcs accelerate, the network converges to the centre, a controlled gold light pulse
 *   3.0-5.0 s  "THE HIDDEN ECONOMICS" in metallic gold + tagline; hold; smooth fade to dark at the end
 *
 * Fixed brand palette (independent of each episode's palette): deep navy, charcoal, metallic gold, white.
 * Pure SVG, no external assets. Use standalone (composition "Intro") or as the `channel_intro` scene type.
 * The matching 5-second sonic signature is generated by hiddeneco/intro.py (assets/brand/intro_signature.wav).
 */
export const INTRO_SECONDS = 5;
export const TAGLINE = 'The Stories Behind Money, Power and the World.';

const NAVY = '#07101F', NAVY2 = '#0C1A30', CHAR = '#14171D', GOLD = '#D9B25F', GOLD_HI = '#FFF0C8', WHITE = '#EEF1F6';

// Financial centres and trade hubs (lat, lon)
const CITIES: [number, number][] = [
  [40.71, -74.0], [51.51, -0.13], [35.68, 139.69], [22.32, 114.17], [1.35, 103.82], [25.2, 55.27], [50.11, 8.68],
  [-23.55, -46.63], [19.08, 72.88], [31.23, 121.47], [47.37, 8.54], [-33.87, 151.21], [37.77, -122.42], [41.88, -87.63],
  [48.86, 2.35], [55.76, 37.62], [-26.2, 28.05], [6.52, 3.38], [24.71, 46.68], [37.57, 126.98],
];
const LINKS: [number, number][] = [
  [0, 1], [1, 5], [5, 8], [8, 4], [4, 3], [3, 2], [2, 12], [12, 0], [0, 7], [9, 2], [16, 1], [17, 1], [11, 4], [7, 16],
  [15, 1], [0, 6], [2, 11], [5, 4], [8, 1], [12, 3], [7, 17], [19, 9],
];

type V3 = [number, number, number];
const toV = (lat: number, lon: number): V3 => {
  const a = (lat * Math.PI) / 180, b = (lon * Math.PI) / 180;
  return [Math.cos(a) * Math.sin(b), Math.sin(a), Math.cos(a) * Math.cos(b)];
};
const slerp = (p: V3, q: V3, u: number): V3 => {
  const d = clamp(p[0] * q[0] + p[1] * q[1] + p[2] * q[2], -1, 1);
  const w = Math.acos(d);
  if (w < 1e-4) return p;
  const s0 = Math.sin((1 - u) * w) / Math.sin(w), s1 = Math.sin(u * w) / Math.sin(w);
  return [p[0] * s0 + q[0] * s1, p[1] * s0 + q[1] * s1, p[2] * s0 + q[2] * s1];
};

export const IntroArt: React.FC<{t: number; W?: number; H?: number}> = ({t, W = 1920, H = 1080}) => {
  const pts = useMemo(() => {
    const n = 900, out: V3[] = [];
    const g = Math.PI * (3 - Math.sqrt(5));
    for (let i = 0; i < n; i++) {
      const y = 1 - (i / (n - 1)) * 2, r = Math.sqrt(1 - y * y), th = g * i;
      out.push([Math.cos(th) * r, y, Math.sin(th) * r]);
    }
    return out;
  }, []);
  const cityV = useMemo(() => CITIES.map(([a, b]) => toV(a, b)), []);
  const cx = W / 2, cy = H * 0.5;
  // camera: slow orbit + dolly in, then the network collapses into the centre
  const rot = -1.2 + t * 0.32 + easeInOut(clamp((t - 1.4) / 1.6)) * 0.9; // accelerating spin
  const tilt = 0.38 - t * 0.03;
  const open = easeOut(clamp(t / 1.1));
  const conv = easeInOut(clamp((t - 1.7) / 1.25)); // 0..1 convergence
  const R = lerp(250, 290, easeOut(clamp(t / 1.6))) * (1 - 0.92 * conv);
  const project = (v: V3): [number, number, number] => {
    const x1 = v[0] * Math.cos(rot) + v[2] * Math.sin(rot);
    const z1 = -v[0] * Math.sin(rot) + v[2] * Math.cos(rot);
    const y1 = v[1] * Math.cos(tilt) - z1 * Math.sin(tilt);
    const z2 = v[1] * Math.sin(tilt) + z1 * Math.cos(tilt);
    const f = 3.2 / (3.2 - z2); // perspective
    return [cx + x1 * R * f, cy - y1 * R * f, z2];
  };
  const globeO = open * (1 - 0.85 * conv) * (t < 3 ? 1 : clamp(1 - (t - 3) / 0.3));
  const pulseT = t - 2.92;
  const pulse = pulseT > 0 ? Math.exp(-pulseT * 3.2) * clamp(pulseT / 0.06) : 0;
  const titleU = easeOut(clamp((t - 3.0) / 0.6));
  const tagU = easeOut(clamp((t - 3.55) / 0.55));
  const outU = easeInOut(clamp((t - 4.62) / 0.38));
  const sheen = lerp(-0.6, 1.6, clamp((t - 3.1) / 1.3));
  const track = lerp(30, 14, easeOut(clamp((t - 3.0) / 1.2)));
  // parallax dust (three depths)
  const dust = Array.from({length: 90}, (_, i) => {
    const depth = 1 + (i % 3);
    const sx = ((i * 211.7) % W + t * (6 + depth * 10) * (i % 2 ? 1 : -1) + W) % W;
    const sy = ((i * 97.3) % H + Math.sin(t * 0.6 + i) * 6 * depth);
    return <circle key={i} cx={sx} cy={sy} r={0.6 + depth * 0.45} fill={i % 7 ? WHITE : GOLD} opacity={(0.05 + 0.05 * depth) * open * (1 - outU)} />;
  });
  return (
    <svg width={W} height={H}>
      <defs>
        <radialGradient id="thei_bg" cx="50%" cy="48%" r="70%">
          <stop offset="0%" stopColor={NAVY2} />
          <stop offset="55%" stopColor={NAVY} />
          <stop offset="100%" stopColor="#03060C" />
        </radialGradient>
        <radialGradient id="thei_pulse">
          <stop offset="0%" stopColor={GOLD_HI} stopOpacity={0.95} />
          <stop offset="35%" stopColor={GOLD} stopOpacity={0.45} />
          <stop offset="100%" stopColor={GOLD} stopOpacity={0} />
        </radialGradient>
        <linearGradient id="thei_gold" x1="0" y1="0" x2="1" y2="0" gradientTransform={`translate(${sheen - 0.5} 0)`}>
          <stop offset="0%" stopColor="#8A6A2E" />
          <stop offset="38%" stopColor={GOLD} />
          <stop offset="50%" stopColor={GOLD_HI} />
          <stop offset="62%" stopColor={GOLD} />
          <stop offset="100%" stopColor="#7C5D26" />
        </linearGradient>
        <linearGradient id="thei_rule" x1="0" x2="1">
          <stop offset="0%" stopColor={GOLD} stopOpacity={0} />
          <stop offset="50%" stopColor={GOLD_HI} />
          <stop offset="100%" stopColor={GOLD} stopOpacity={0} />
        </linearGradient>
        <filter id="thei_glow" x="-50%" y="-50%" width="200%" height="200%"><feGaussianBlur stdDeviation="6" /></filter>
        <clipPath id="thei_reveal"><rect x={cx - 900 * titleU} y={0} width={1800 * titleU} height={H} /></clipPath>
      </defs>
      <rect width={W} height={H} fill="url(#thei_bg)" />
      <rect width={W} height={H} fill={CHAR} opacity={0.25} />
      {dust}
      {/* globe points (back faded, front brighter) */}
      <g opacity={globeO}>
        {pts.map((v, i) => {
          const [x, y, z] = project(v);
          const front = (z + 1) / 2;
          return <circle key={i} cx={x} cy={y} r={1.1 + 1.9 * front * (1 - conv * 0.6)} fill={front > 0.55 ? WHITE : '#6C7B95'} opacity={0.18 + 0.7 * front * front} />;
        })}
      </g>
      {/* arcs between centres, lifted off the sphere, drawn progressively; accelerating packets */}
      <g opacity={open * (1 - outU) * (t < 3.05 ? 1 : clamp(1 - (t - 3.05) / 0.25))}>
        {LINKS.map(([a, b], i) => {
          const start = 0.15 + i * 0.045;
          const u = easeInOut(clamp((t - start) / 0.85));
          if (u <= 0) return null;
          const n = 26, pts2: [number, number, number][] = [];
          for (let k = 0; k <= n; k++) {
            const q = (k / n) * u;
            const s = slerp(cityV[a], cityV[b], q);
            const lift = 1 + 0.14 * Math.sin(Math.PI * q);
            pts2.push(project([s[0] * lift, s[1] * lift, s[2] * lift]));
          }
          const vis = pts2.reduce((m, p) => m + (p[2] > -0.15 ? 1 : 0), 0) / pts2.length;
          const d = 'M' + pts2.map((p) => `${p[0].toFixed(1)},${p[1].toFixed(1)}`).join(' L');
          const head = pts2[pts2.length - 1];
          const speed = 0.5 + 2.6 * clamp((t - 1.5) / 1.4);
          const pk = (t * speed + i * 0.13) % 1;
          const pkV = (() => { const s = slerp(cityV[a], cityV[b], pk * u); const l = 1 + 0.14 * Math.sin(Math.PI * pk * u); return project([s[0] * l, s[1] * l, s[2] * l]); })();
          return (
            <g key={i} opacity={0.25 + 0.75 * vis}>
              <path d={d} fill="none" stroke={GOLD} strokeWidth={2.4} opacity={0.75} />
              <path d={d} fill="none" stroke={GOLD} strokeWidth={8} opacity={0.2} filter="url(#thei_glow)" />
              {u < 1 && <circle cx={head[0]} cy={head[1]} r={3.5} fill={GOLD_HI} />}
              {u >= 1 && <circle cx={pkV[0]} cy={pkV[1]} r={2.6} fill={GOLD_HI} opacity={0.9} />}
            </g>
          );
        })}
        {cityV.map((v, i) => {
          const [x, y, z] = project(v);
          if (z < -0.1) return null;
          const on = clamp((t - 0.2 - i * 0.03) / 0.3);
          return <circle key={i} cx={x} cy={y} r={3 + 2 * Math.sin(t * 5 + i) * 0.5} fill={GOLD_HI} opacity={on * (0.5 + 0.5 * (z + 1) / 2)} />;
        })}
      </g>
      {/* convergence streaks: every visible centre sends light into the core */}
      {conv > 0 && conv < 1 && t < 3.0 && cityV.map((v, i) => {
        const [x, y, z] = project(v);
        if (z < 0) return null;
        const k = clamp(conv * 1.3 - i * 0.012);
        const x2 = lerp(x, cx, k), y2 = lerp(y, cy, k);
        return <line key={'s' + i} x1={lerp(x, cx, Math.max(0, k - 0.35))} y1={lerp(y, cy, Math.max(0, k - 0.35))} x2={x2} y2={y2}
          stroke={GOLD_HI} strokeWidth={2} strokeLinecap="round" opacity={0.7 * (1 - conv * 0.3)} />;
      })}
      {/* gold light pulse */}
      {pulse > 0.01 && (
        <g>
          <circle cx={cx} cy={cy} r={120 + 760 * (1 - Math.exp(-pulseT * 2.4))} fill="url(#thei_pulse)" opacity={pulse * 0.85} />
          <circle cx={cx} cy={cy} r={60 + 900 * (1 - Math.exp(-pulseT * 3))} fill="none" stroke={GOLD} strokeWidth={2} opacity={pulse * 0.6} />
        </g>
      )}
      {/* core glow before the pulse */}
      {t > 1.8 && t < 3.1 && <circle cx={cx} cy={cy} r={20 + 30 * conv} fill={GOLD_HI} opacity={0.5 * conv} filter="url(#thei_glow)" />}
      {/* brand reveal */}
      <g opacity={1 - outU}>
        <g clipPath="url(#thei_reveal)" transform={`translate(0 ${10 * (1 - titleU)})`}>
          <text x={cx} y={cy + 18} textAnchor="middle" fontFamily="Inter Display, Inter, sans-serif" fontWeight={800} fontSize={90}
            letterSpacing={track} fill="url(#thei_gold)">THE HIDDEN ECONOMICS</text>
        </g>
        <rect x={cx - 520 * easeOut(clamp((t - 3.3) / 0.6))} y={cy + 58} width={1040 * easeOut(clamp((t - 3.3) / 0.6))} height={2} fill="url(#thei_rule)" />
        <text x={cx} y={cy + 122 + 12 * (1 - tagU)} textAnchor="middle" fontFamily="Inter, sans-serif" fontWeight={400} fontSize={36}
          letterSpacing={2.5} fill={WHITE} opacity={0.88 * tagU}>{TAGLINE}</text>
      </g>
      {/* vignette + final fade to dark (clean hand-off into the documentary) */}
      <rect width={W} height={H} fill="#000" opacity={outU * 0.92} />
    </svg>
  );
};

/** Standalone composition (5 s). */
export const TheHiddenEconomicsIntro: React.FC = () => {
  const frame = useCurrentFrame();
  const {fps, width, height} = useVideoConfig();
  return <AbsoluteFill style={{backgroundColor: '#000'}}><IntroArt t={frame / fps} W={width} H={height} /></AbsoluteFill>;
};
